const fs = require("fs");
const path = require("path");

const INPUT_JSON = path.join(__dirname, "..", "contract", "contract.json");
const OUTPUT_DIR = path.join(__dirname, "..", "src");

function toPascalCase(value) {
  return String(value)
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join("");
}

function toConstName(value) {
  return String(value)
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
}

function sanitizeEnumValue(value) {
  return String(value).trim().replace(/^["']|["']$/g, "");
}

function mapTsType(variable) {
  if (variable.enumValues && variable.enumValues.length > 0) {
    return toPascalCase(variable.name);
  }

  switch (variable.dataType) {
    case "string":
      return "string";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "object":
      return "Record<string, unknown>";
    case "array":
      return "unknown[]";
    case "datetime":
      return "string";
    default:
      return "unknown";
  }
}

function generateEnumsTs(contract) {
  const enumVariables = contract.variables.filter(
    (v) => Array.isArray(v.enumValues) && v.enumValues.length > 0
  );

  const lines = [];
  lines.push("// AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.");
  lines.push("// Generated by scripts/pass2-generate-artifacts.js");
  lines.push("");

  for (const variable of enumVariables) {
    const typeName = toPascalCase(variable.name);
    const constName = `${toConstName(variable.name)}_VALUES`;
    const enumValues = variable.enumValues.map(sanitizeEnumValue);

    lines.push(`export const ${constName} = [`);
    for (const value of enumValues) {
      lines.push(`  "${value}",`);
    }
    lines.push(`] as const;`);
    lines.push("");
    lines.push(`export type ${typeName} = typeof ${constName}[number];`);
    lines.push("");
  }

  return lines.join("\n");
}

function generateFieldNamesTs(contract) {
  const lines = [];
  lines.push("// AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.");
  lines.push("// Generated by scripts/pass2-generate-artifacts.js");
  lines.push("");
  lines.push("export const FIELD_NAMES = {");

  for (const variable of contract.variables) {
    lines.push(`  ${variable.name}: "${variable.name}",`);
  }

  lines.push("} as const;");
  lines.push("");
  lines.push("export type FieldName = keyof typeof FIELD_NAMES;");
  lines.push("");

  return lines.join("\n");
}

function generateTypesTs(contract) {
  const lines = [];
  lines.push("// AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.");
  lines.push("// Generated by scripts/pass2-generate-artifacts.js");
  lines.push("");

  const enumVariables = contract.variables.filter(
    (v) => Array.isArray(v.enumValues) && v.enumValues.length > 0
  );

  if (enumVariables.length > 0) {
    const imports = enumVariables.map((v) => toPascalCase(v.name)).sort();
    lines.push(`import type { ${imports.join(", ")} } from "../constants/enums";`);
    lines.push("");
  }

  const payloadTypeEntries = Object.entries(contract.payloadTypes || {});

  for (const [payloadTypeName, fieldNames] of payloadTypeEntries) {
    lines.push(`export interface ${payloadTypeName} {`);

    for (const fieldName of fieldNames) {
      const variable = contract.variables.find((v) => v.name === fieldName);
      const tsType = variable ? mapTsType(variable) : "unknown";
      const comment = variable?.purpose ? ` // ${variable.purpose}` : "";
      lines.push(`  ${fieldName}: ${tsType};${comment}`);
    }

    lines.push("}");
    lines.push("");
  }

  return lines.join("\n");
}

function generateServicesTs(contract) {
  const lines = [];
  lines.push("// AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY.");
  lines.push("// Generated by scripts/pass2-generate-artifacts.js");
  lines.push("");

  for (const fn of contract.functions) {
    if (fn.purpose) {
      lines.push("/**");
      lines.push(` * ${fn.purpose}`);
      lines.push(" */");
    }
    lines.push(`export function ${fn.name}(...args: unknown[]): unknown {`);
    lines.push(`  throw new Error("${fn.name} is not implemented yet.");`);
    lines.push("}");
    lines.push("");
  }

  return lines.join("\n");
}

function writeFile(relativePath, contents) {
  const fullPath = path.join(OUTPUT_DIR, relativePath);
  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  fs.writeFileSync(fullPath, contents, "utf8");
  console.log(`Generated -> ${fullPath}`);
}

function main() {
  if (!fs.existsSync(INPUT_JSON)) {
    throw new Error(`Contract JSON not found: ${INPUT_JSON}`);
  }

  const contract = JSON.parse(fs.readFileSync(INPUT_JSON, "utf8"));

  writeFile("constants/enums.ts", generateEnumsTs(contract));
  writeFile("constants/fieldNames.ts", generateFieldNamesTs(contract));
  writeFile("types/precheck.ts", generateTypesTs(contract));
  writeFile("services/precheck/index.ts", generateServicesTs(contract));
}

main();